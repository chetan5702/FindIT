import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { readIdentityToken } from './mail-helper'

test('institutional verification and password recovery revoke the previous session', async ({ page, browser, baseURL }) => {
  test.skip(process.env.FINDIT_REQUIRE_EMAIL_VERIFICATION !== 'true' || !process.env.FINDIT_MAIL_DIRECTORY, 'Requires the private verified-identity test stack')
  test.setTimeout(90_000)
  const email = `identity-${randomUUID()}@suh.edu.in`
  await page.goto('/register', { waitUntil: 'domcontentloaded' })
  await page.locator('#full_name').fill('Identity Student')
  await page.locator('#register-email').fill(email)
  await page.locator('#register-password').fill('BrowserTest12345!')
  await page.locator('#confirm').fill('BrowserTest12345!')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Check your institutional email' })).toBeVisible()
  expect((await page.request.get('/api/v1/auth/me')).status()).toBe(401)
  const verify = await readIdentityToken(email, 'verify-email')
  await page.goto(`/verify-email#token=${verify}`, { waitUntil: 'domcontentloaded' })
  await expect(page).toHaveURL(/\/verify-email$/)
  await page.locator('#new-password').fill('BrowserTest12345!')
  await page.locator('#confirm-password').fill('BrowserTest12345!')
  await page.getByRole('button', { name: 'Confirm email verification', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Email verified')
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.locator('#email').fill(email)
  await page.locator('#password').fill('BrowserTest12345!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/app$/)
  const recovery = await browser.newContext({ baseURL, ignoreHTTPSErrors: process.env.PLAYWRIGHT_IGNORE_HTTPS_ERRORS === 'true' })
  try {
    const other = await recovery.newPage()
    await other.goto('/forgot-password', { waitUntil: 'domcontentloaded' })
    await other.locator('#identity-email').fill(email)
    await other.getByRole('button', { name: 'Send email', exact: true }).click()
    await expect(other.getByRole('status')).toContainText('If the account is eligible')
    const reset = await readIdentityToken(email, 'reset-password')
    await other.goto(`/reset-password#token=${reset}`, { waitUntil: 'domcontentloaded' })
    await other.locator('#new-password').fill('RecoveredPassword678!')
    await other.locator('#confirm-password').fill('RecoveredPassword678!')
    await other.getByRole('button', { name: 'Reset password', exact: true }).click()
    await expect(other.getByRole('status')).toContainText('Password reset')
    expect((await page.request.get('/api/v1/auth/me')).status()).toBe(401)
    await other.goto('/login', { waitUntil: 'domcontentloaded' })
    await other.locator('#email').fill(email)
    await other.locator('#password').fill('RecoveredPassword678!')
    await other.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(other).toHaveURL(/\/app$/)
  } finally { await recovery.close() }
})
